// Copies the app's UiTM HEA calendar reader into the admin website, so the
// admin compares community submissions with exactly what students' apps get:
//
//   node scripts/sync-uitm-hea-parser.mjs   (run in admin-web)
//
// Source: gradeup-mobile/src/lib/uitmAcademicCalendar.ts. Two mechanical
// changes: the app's type import is replaced by the same types written out,
// and fetch(HEA_CALENDAR_URL) goes through heaFetch, because a browser can't
// read hea.uitm.edu.my directly (the admin passes the page in from the
// admin_uitm_hea server function).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';

const src = resolve('../gradeup-mobile/src/lib/uitmAcademicCalendar.ts');
const out = resolve('src/vendor/uitm/uitmAcademicCalendar.ts');
let s = readFileSync(src, 'utf8');

const typeImport = "import type { AcademicCalendar, AcademicPeriod, AcademicPeriodType } from '@/src/types';";
if (!s.includes(typeImport)) throw new Error('The app file no longer starts with the expected type import. Update this script.');
const fetchCalls = (s.match(/await fetch\(HEA_CALENDAR_URL\)/g) || []).length;
if (fetchCalls === 0) throw new Error('No fetch(HEA_CALENDAR_URL) found in the app file. Update this script.');

s = s.replace(typeImport, `// GENERATED by admin-web/scripts/sync-uitm-hea-parser.mjs from
// gradeup-mobile/src/lib/uitmAcademicCalendar.ts. Do not edit by hand.
/* eslint-disable */
// @ts-nocheck — copied app code, type-checked in the app project.

export type AcademicPeriodType =
  | 'lecture' | 'orientation' | 'registration' | 'test' | 'revision' | 'exam'
  | 'break' | 'special_break' | 'holiday' | 'industrial_training' | 'other';
export interface AcademicPeriod { type: AcademicPeriodType; label: string; startDate: string; endDate: string }
export interface AcademicCalendar {
  id: string; userId?: string; semesterLabel: string; startDate: string; endDate: string; totalWeeks: number;
  breakStartDate?: string; breakEndDate?: string; periods?: AcademicPeriod[];
}

let heaFetch: (url: string) => Promise<Response> = (url) => fetch(url);
/** The admin passes the HEA page in (see lib/uitmHea.ts). */
export function setHeaFetch(fn: (url: string) => Promise<Response>) { heaFetch = fn; }`);
s = s.replace(/await fetch\(HEA_CALENDAR_URL\)/g, 'await heaFetch(HEA_CALENDAR_URL)');

mkdirSync(resolve('src/vendor/uitm'), { recursive: true });
writeFileSync(out, s);
console.log(`Copied the UiTM HEA reader (${fetchCalls} HEA fetch call(s) routed through heaFetch) to ${out}`);
