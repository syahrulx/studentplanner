// Copies the app's UiTM HEA calendar parser into the admin website, so the
// admin compares community submissions with exactly what students' apps get:
//
//   node scripts/sync-uitm-hea-parser.mjs   (run in admin-web)
//
// Sources: gradeup-mobile/src/lib/uitmHeaParser.ts and uitmHeaTypes.ts (the
// same files the app's uitm_calendar Edge Function copies). They only read
// HTML and never fetch, so they are copied unchanged apart from a header.
import { readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { resolve } from 'node:path';

const header = `// GENERATED by admin-web/scripts/sync-uitm-hea-parser.mjs from
// gradeup-mobile/src/lib. Do not edit by hand: edit the app file and re-run.
/* eslint-disable */
// @ts-nocheck — copied app code, type-checked in the app project.
`;

mkdirSync(resolve('src/vendor/uitm'), { recursive: true });
for (const name of ['uitmHeaParser.ts', 'uitmHeaTypes.ts']) {
  const src = readFileSync(resolve('../gradeup-mobile/src/lib', name), 'utf8');
  writeFileSync(resolve('src/vendor/uitm', name), header + src);
  console.log(`Wrote src/vendor/uitm/${name}`);
}

// Older copy (whole app module with a fetch hook); replaced by the parser.
const old = resolve('src/vendor/uitm/uitmAcademicCalendar.ts');
if (existsSync(old)) {
  rmSync(old);
  console.log('Removed old src/vendor/uitm/uitmAcademicCalendar.ts');
}
