#!/usr/bin/env node
/**
 * Copies the UiTM HEA parser into the Edge Function folder.
 *
 *   node scripts/sync-uitm-hea-parser.js          write the copies
 *   node scripts/sync-uitm-hea-parser.js --check  fail if they are out of date
 *
 * The app and the uitm_calendar Edge Function must read HEA the same way, so
 * src/lib/uitmHeaParser.ts and src/lib/uitmHeaTypes.ts are the only sources.
 * Deno needs explicit .ts extensions on relative imports, so that is the only
 * change made to the copies.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const pairs = [
  ['src/lib/uitmHeaParser.ts', 'supabase/functions/_shared/uitmHeaParser.ts'],
  ['src/lib/uitmHeaTypes.ts', 'supabase/functions/_shared/uitmHeaTypes.ts'],
];
const banner = '// GENERATED by scripts/sync-uitm-hea-parser.js from the matching file in\n// src/lib. Do not edit here: edit src/lib and run the script.\n';

let stale = false;
for (const [from, to] of pairs) {
  const src = fs.readFileSync(path.join(root, from), 'utf8');
  const out = banner + src.replace(/from '\.\/(uitmHea[A-Za-z]+)'/g, "from './$1.ts'");
  const dest = path.join(root, to);
  const current = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : '';
  if (current === out) continue;
  if (process.argv.includes('--check')) {
    console.error(`Out of date: ${to}. Run: node scripts/sync-uitm-hea-parser.js`);
    stale = true;
  } else {
    fs.writeFileSync(dest, out);
    console.log(`Wrote ${to}`);
  }
}
if (stale) process.exit(1);
