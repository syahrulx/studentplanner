#!/usr/bin/env node
/**
 * Copies the RenTaman avatar drawing code into the app.
 *
 *   node scripts/sync-rentaman-avatar.js          write the copies
 *   node scripts/sync-rentaman-avatar.js --check  fail if they are out of date
 *
 * Source: admin-web/src/vendor/study-world (itself the website's
 * src/lib/study-world). The app draws the same avatars from the same code,
 * so a look saved on rencana.app appears the same on the profile.
 */
const fs = require('fs');
const path = require('path');

const repo = path.resolve(__dirname, '..', '..');
const from = path.join(repo, 'admin-web/src/vendor/study-world');
const to = path.join(repo, 'gradeup-mobile/src/vendor/rentaman');
const banner = '// GENERATED by gradeup-mobile/scripts/sync-rentaman-avatar.js from\n// admin-web/src/vendor/study-world. Do not edit here.\n';

const files = ['avatar.ts', ...fs.readdirSync(path.join(from, 'avatar-items')).filter((f) => f.endsWith('.ts')).map((f) => `avatar-items/${f}`)];
let stale = false;
for (const f of files) {
  const out = banner + fs.readFileSync(path.join(from, f), 'utf8');
  const dest = path.join(to, f);
  const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : '';
  if (cur === out) continue;
  if (process.argv.includes('--check')) {
    console.error(`Out of date: src/vendor/rentaman/${f}. Run: node scripts/sync-rentaman-avatar.js`);
    stale = true;
  } else {
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, out);
  }
}
if (stale) process.exit(1);
console.log(`rentaman avatar: ${files.length} files in step`);
